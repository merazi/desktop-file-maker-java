    private void btnOpenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOpenActionPerformed
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Open .desktop File to Edit");
        chooser.setFileHidingEnabled(!chkShowHidden.isSelected());
        chooser.setFileFilter(new FileNameExtensionFilter("Desktop Entry Files (*.desktop)", "desktop"));

        File defaultDir = new File(System.getProperty("user.home"), ".local/share/applications");
        if (defaultDir.exists()) {
            chooser.setCurrentDirectory(defaultDir);
        }

        int result = chooser.showOpenDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            File selectedFile = chooser.getSelectedFile();
            try {
                openDesktopFile(selectedFile);
            } catch (Exception ex) {
                logger.log(Level.SEVERE, "Failed to parse .desktop file", ex);
                JOptionPane.showMessageDialog(this,
                        "Error reading .desktop file:\n" + ex.getMessage(),
                        "Open Error",
                        JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnOpenActionPerformed

