    private void openDesktopFile(File file) throws Exception {
        java.util.List<String> lines = java.nio.file.Files.readAllLines(file.toPath(), StandardCharsets.UTF_8);
        
        String name = "";
        String comment = "";
        String exec = "";
        String path = "";
        String icon = "";
        String categories = "";
        boolean terminal = false;
        boolean startupNotify = false;
        boolean inDesktopEntry = false;

        for (String line : lines) {
            line = line.trim();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            if (line.startsWith("[") && line.endsWith("]")) {
                inDesktopEntry = line.equalsIgnoreCase("[Desktop Entry]");
                continue;
            }
            if (!inDesktopEntry) {
                continue;
            }

            int eqIdx = line.indexOf('=');
            if (eqIdx <= 0) {
                continue;
            }

            String key = line.substring(0, eqIdx).trim();
            String val = line.substring(eqIdx + 1).trim();

            if (key.equalsIgnoreCase("Name")) {
                name = val;
            } else if (key.equalsIgnoreCase("Comment")) {
                comment = val;
            } else if (key.equalsIgnoreCase("Exec")) {
                exec = val;
            } else if (key.equalsIgnoreCase("Path")) {
                path = val;
            } else if (key.equalsIgnoreCase("Icon")) {
                icon = val;
            } else if (key.equalsIgnoreCase("Categories")) {
                categories = val;
            } else if (key.equalsIgnoreCase("Terminal")) {
                terminal = val.equalsIgnoreCase("true") || val.equals("1") || val.equalsIgnoreCase("yes");
            } else if (key.equalsIgnoreCase("StartupNotify")) {
                startupNotify = val.equalsIgnoreCase("true") || val.equals("1") || val.equalsIgnoreCase("yes");
            }
        }

        txtName.setText(name);
        txtComment.setText(comment);
        txtCommand.setText(exec);
        txtWorkDir.setText(path);
        txtIcon.setText(icon);
        txtCategories.setText(categories);
        chkTerminal.setSelected(terminal);
        chkStartupNotify.setSelected(startupNotify);
        updateIconPreview();

        setTitle("Create Launcher - Editing: " + file.getName());
    }

    private void saveDesktopFile(File file, String name, String comment, String command,
                                 String workDir, String icon, String categories,
                                 boolean terminal, boolean startupNotify) throws Exception {
        StringBuilder sb = new StringBuilder();
        sb.append("[Desktop Entry]\n");
        sb.append("Version=1.0\n");
        sb.append("Type=Application\n");
        sb.append("Name=").append(name).append("\n");
        
        if (!comment.isEmpty()) {
            sb.append("Comment=").append(comment).append("\n");
        }
        
        sb.append("Exec=").append(command).append("\n");
        
        if (!workDir.isEmpty()) {
            sb.append("Path=").append(workDir).append("\n");
        }
        
        if (!icon.isEmpty()) {
            sb.append("Icon=").append(icon).append("\n");
        }
        
        if (!categories.isEmpty()) {
            sb.append("Categories=").append(categories).append("\n");
        }
        
        sb.append("Terminal=").append(terminal ? "true" : "false").append("\n");
        sb.append("StartupNotify=").append(startupNotify ? "true" : "false").append("\n");

        try (OutputStreamWriter writer = new OutputStreamWriter(new FileOutputStream(file), StandardCharsets.UTF_8)) {
            writer.write(sb.toString());
        }
    }

