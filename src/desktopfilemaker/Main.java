    /**
     * Updates the icon preview label based on the icon text field.
     */
    private void updateIconPreview() {
        String iconPath = txtIcon.getText().trim();
        if (iconPath.isEmpty()) {
            lblIconPreview.setIcon(null);
            lblIconPreview.setText("N/A");
            return;
        }

        File iconFile = new File(iconPath);
        if (iconFile.exists() && iconFile.isFile()) {
            try {
                ImageIcon originalIcon = new ImageIcon(iconFile.getAbsolutePath());
                Image scaledImage = originalIcon.getImage().getScaledInstance(32, 32, Image.SCALE_SMOOTH);
                lblIconPreview.setIcon(new ImageIcon(scaledImage));
                lblIconPreview.setText("");
                return;
            } catch (Exception ex) {
                logger.log(Level.FINE, "Failed to render image file preview", ex);
            }
        }
        
        lblIconPreview.setIcon(null);
        lblIconPreview.setText("[" + iconPath + "]");
    }

