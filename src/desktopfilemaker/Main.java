    private void btnSelectCategoriesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSelectCategoriesActionPerformed
        javax.swing.JDialog dialog = new javax.swing.JDialog(this, "Select Categories", true);
        dialog.setLayout(new java.awt.BorderLayout(10, 10));

        javax.swing.JPanel listPanel = new javax.swing.JPanel(new java.awt.GridLayout(0, 2, 5, 5));
        listPanel.setBorder(javax.swing.BorderFactory.createEmptyBorder(10, 10, 10, 10));

        String[] standardCategories = {
            "AudioVideo", "Development", "Education", "Game", 
            "Graphics", "Network", "Office", "Settings", "System", "Utility"
        };

        String currentCats = txtCategories.getText().trim();
        java.util.List<javax.swing.JCheckBox> checkBoxes = new java.util.ArrayList<>();

        for (String cat : standardCategories) {
            javax.swing.JCheckBox cb = new javax.swing.JCheckBox(cat);
            if (currentCats.contains(cat + ";") || currentCats.contains(cat)) {
                cb.setSelected(true);
            }
            checkBoxes.add(cb);
            listPanel.add(cb);
        }

        javax.swing.JPanel customPanel = new javax.swing.JPanel(new java.awt.BorderLayout(5, 5));
        customPanel.setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 10, 5, 10));
        customPanel.add(new javax.swing.JLabel("Custom (semicolon separated):"), java.awt.BorderLayout.WEST);
        javax.swing.JTextField txtCustom = new javax.swing.JTextField();
        customPanel.add(txtCustom, java.awt.BorderLayout.CENTER);

        javax.swing.JPanel centerPanel = new javax.swing.JPanel(new java.awt.BorderLayout());
        centerPanel.add(listPanel, java.awt.BorderLayout.CENTER);
        centerPanel.add(customPanel, java.awt.BorderLayout.SOUTH);

        javax.swing.JPanel btnPanel = new javax.swing.JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.RIGHT));
        javax.swing.JButton btnOk = new javax.swing.JButton("OK");
        javax.swing.JButton btnDialogCancel = new javax.swing.JButton("Cancel");

        btnOk.addActionListener(e -> {
            StringBuilder sb = new StringBuilder();
            for (javax.swing.JCheckBox cb : checkBoxes) {
                if (cb.isSelected()) {
                    sb.append(cb.getText()).append(";");
                }
            }
            String custom = txtCustom.getText().trim();
            if (!custom.isEmpty()) {
                for (String part : custom.split(";")) {
                    String trimmed = part.trim();
                    if (!trimmed.isEmpty()) {
                        sb.append(trimmed).append(";");
                    }
                }
            }
            txtCategories.setText(sb.toString());
            dialog.dispose();
        });

        btnDialogCancel.addActionListener(e -> dialog.dispose());

        btnPanel.add(btnOk);
        btnPanel.add(btnDialogCancel);

        dialog.add(centerPanel, java.awt.BorderLayout.CENTER);
        dialog.add(btnPanel, java.awt.BorderLayout.SOUTH);
        dialog.pack();
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
    }//GEN-LAST:event_btnSelectCategoriesActionPerformed

