    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        String name = txtName.getText().trim();
        String command = txtCommand.getText().trim();
        
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a Name for the launcher.", "Input Error", JOptionPane.WARNING_MESSAGE);
            txtName.requestFocus();
            return;
        }

        if (command.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a Command for the launcher.", "Input Error", JOptionPane.WARNING_MESSAGE);
            txtCommand.requestFocus();
            return;
        }

        String comment = txtComment.getText().trim();
        String workDir = txtWorkDir.getText().trim();
        String icon = txtIcon.getText().trim();
        String categories = txtCategories.getText().trim();
        if (!categories.isEmpty() && !categories.endsWith(";")) {
            categories += ";";
        }
        
        boolean startupNotify = chkStartupNotify.isSelected();
        boolean terminal = chkTerminal.isSelected();

        String userHome = System.getProperty("user.home");
        File defaultDir = new File(userHome, ".local/share/applications");
        if (!defaultDir.exists()) {
            defaultDir.mkdirs();
        }
        if (!defaultDir.exists()) {
            defaultDir = new File(userHome, "Desktop");
        }
        if (!defaultDir.exists()) {
            defaultDir = new File(userHome);
        }

        String sanitizedName = name.replaceAll("[^a-zA-Z0-9._-]", "_").toLowerCase();
        if (sanitizedName.isEmpty()) {
            sanitizedName = "launcher";
        }
        File suggestedFile = new File(defaultDir, sanitizedName + ".desktop");

        JFileChooser chooser = new JFileChooser(defaultDir);
        chooser.setDialogTitle("Save .desktop File");
        chooser.setFileHidingEnabled(!chkShowHidden.isSelected());
        chooser.setSelectedFile(suggestedFile);
        chooser.setFileFilter(new FileNameExtensionFilter("Desktop Entry Files (*.desktop)", "desktop"));

        int result = chooser.showSaveDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            File destFile = chooser.getSelectedFile();
            if (!destFile.getName().toLowerCase().endsWith(".desktop")) {
                destFile = new File(destFile.getParentFile(), destFile.getName() + ".desktop");
            }

            if (destFile.exists()) {
                int confirm = JOptionPane.showConfirmDialog(this,
                        "File '" + destFile.getName() + "' already exists.\nDo you want to overwrite it?",
                        "Confirm Overwrite",
                        JOptionPane.YES_NO_OPTION,
                        JOptionPane.QUESTION_MESSAGE);
                if (confirm != JOptionPane.YES_OPTION) {
                    return;
                }
            }

            try {
                saveDesktopFile(destFile, name, comment, command, workDir, icon, categories, terminal, startupNotify);
                destFile.setExecutable(true, false);

                JOptionPane.showMessageDialog(this,
                        "Launcher successfully created at:\n" + destFile.getAbsolutePath(),
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE);
                
                clearFields();
            } catch (Exception ex) {
                logger.log(Level.SEVERE, "Failed to create .desktop file", ex);
                JOptionPane.showMessageDialog(this,
                        "Error saving file:\n" + ex.getMessage(),
                        "Save Error",
                        JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnCreateActionPerformed

